let currentLanguage = localStorage.getItem('language') || 'zh';

function setLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem('language', lang);
  document.documentElement.lang = lang;
  updateTranslations();
}

// Resolve a key: current language first, then the other language, then the
// raw key as a last-resort. This means a missing translation in zh will fall
// back to en (and vice-versa) instead of rendering the template key.
function getTranslation(key) {
  if (translations[currentLanguage] && translations[currentLanguage][key] !== undefined) {
    return translations[currentLanguage][key];
  }
  var other = currentLanguage === 'zh' ? 'en' : 'zh';
  if (translations[other] && translations[other][key] !== undefined) {
    return translations[other][key];
  }
  return key;
}

// Re-apply translations to every [data-i18n] node, plus the top #page-title.
// Safe to call any number of times. After this returns, newly inserted
// modals (e.g. Recurring / Reports) will pick up the current language
// automatically as long as they include data-i18n attributes.
function updateTranslations() {
  // First pass: save original Chinese/English text from HTML for elements
  // that were not previously translated.
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    if (!el.dataset.originalText) {
      el.dataset.originalText = el.textContent;
    }
  });
  var pageTitle = document.getElementById('page-title');
  if (pageTitle && !pageTitle.dataset.originalText) {
    pageTitle.dataset.originalText = pageTitle.textContent;
  }

  // Second pass: apply translations. If the current language has no entry,
  // fall back to the OTHER language, then finally to the HTML original.
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    var translation = getTranslation(key);
    if (typeof translation === 'string') {
      el.textContent = translation;
    } else {
      el.textContent = el.dataset.originalText;
    }
  });

  // Update page title based on the currently visible section. The key is the
  // section id without the trailing "-section" (e.g. "recurring", "reports").
  var activeSection = document.querySelector('.section-content.active');
  if (activeSection && pageTitle) {
    var sectionId = activeSection.id.replace('-section', '');
    var titleTr = getTranslation(sectionId);
    if (typeof titleTr === 'string') {
      pageTitle.textContent = titleTr;
    } else {
      pageTitle.textContent = sectionId;
    }
  }
}

